/* eslint-disable @typescript-eslint/no-require-imports -- Node CommonJS test harness compiles the TypeScript calculation module. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
require.extensions['.ts'] = (mod, file) => mod._compile(ts.transpileModule(fs.readFileSync(file,'utf8'), { compilerOptions:{ module:ts.ModuleKind.CommonJS, target:ts.ScriptTarget.ES2022 } }).outputText,file);
const {treasurySummary} = require('../lib/treasury.ts');
const ledger={sales:[],purchases:[],payments:[],allocations:[],movements:[],shares:[]};
const settings={opening_main:1000,opening_petty:100,opening_capital:1000,working_reserve:600,other_reserve:50,tax_reserve:50};
const today='2026-11-24';
const entry=(kind,amount)=>({id:kind,kind,amount,date:today,description:'Prueba'});
let treasury={settings,entries:[]};
assert.equal(treasurySummary(ledger,{settings:null,entries:[]},today).withdrawable,null);
let value=treasurySummary(ledger,treasury,today);
assert.equal(value.liquid,1100);assert.equal(value.withdrawable,400);
treasury.entries=[entry('to_petty',200)];value=treasurySummary(ledger,treasury,today);
assert.equal(value.main,800);assert.equal(value.petty,300);assert.equal(value.liquid,1100);
treasury.entries.push(entry('petty_expense',20),entry('contribution',100),entry('owner_draw',50));
value=treasurySummary(ledger,treasury,today);
assert.equal(value.liquid,1130);assert.equal(value.capital,1100);assert.equal(value.withdrawable,430);
treasury.entries.push(entry('capital_return',100));value=treasurySummary(ledger,treasury,today);
assert.equal(value.capital,1000);assert.equal(value.liquid,1030);
ledger.purchases.push({id:'purchase',issued:today,gross:200,vat:0,eligible:0,qty:1,kind:'producto'});
assert.equal(treasurySummary(ledger,treasury,today).withdrawable,130);
ledger.payments.push({id:'payment',purchase_id:'purchase',amount:200,paid_on:today});
value=treasurySummary(ledger,treasury,today);
assert.equal(value.payable,0);assert.equal(value.withdrawable,130,'Paying a reserved debt must not release money twice');
treasury.entries.push(entry('owner_draw',1000));
assert.equal(treasurySummary(ledger,treasury,today).withdrawable,null,'A negative account requires reconciliation');
const unknown={...ledger,sales:[{id:'sale',issued:today,gross:115,vat:null,lines:[]} ]};
assert.equal(treasurySummary(unknown,{settings:{...settings,tax_reserve:null},entries:[]},today).withdrawable,null);
console.log('Treasury: opening balances, transfers, capital, expenses, withdrawals, debt payments and unknown VAT passed.');
